// ============================================================
// צבעי המשמרות.
//
// עד עכשיו כל תבנית נשאה hex משלה — כחול, סגול, כתום — שנבחרו לפני
// שהיה מותג. על רקע קרם הם צעקו, ולא היה שום קשר בינם לבין הלוגו.
//
// במקומם יש כאן **סולם אחד בתוך משפחת הצבעים של המותג**: מנטה בהירה
// לבוקר, ומשם כהה והולך עד הטלה העמוק בלילה. הסולם עצמו נושא מידע —
// ככל שהמשמרת מאוחרת יותר, הצבע כהה יותר — ולכן לוח שבועי נקרא כיום
// ולילה עוד לפני שקוראים את השעות בו.
//
// הצבעים נשמרים כ-hex ולא כטוקנים כי הם יורדים לבסיס הנתונים, נצבעים
// על גבי קנבס בשיתוף התמונה, ומשמשים ב-Recharts — שלושה מקומות שבהם
// `rgb(var(--x))` לא מגיע.
// ============================================================

/** הסולם. בהיר = מוקדם, כהה = מאוחר. */
export const SHIFT_TONES = {
  morning: "#7FC0AE", // מנטה בהירה
  afternoon: "#4C9585", // הטורקיז של הלוגו
  evening: "#2F7A6B",
  night: "#1C3B37", // הטלה העמוק של הכיתוב בלוגו
  custom: "#5E8F86",
};

/**
 * הצבעים שהמוצר חילק לפני המיתוג. שיבוץ קיים בבסיס הנתונים עדיין נושא
 * אותם, ולכן הם ממופים מחדש בקריאה — בלי מיגרציה, ובלי שהמשתמש יראה
 * לוח חצי כחול וחצי טורקיז אחרי העדכון.
 */
const LEGACY = new Set([
  "#3b82f6", "#6366f1", "#8b5cf6", "#f59e0b", "#10b981",
  "#06b6d4", "#7c3aed", "#f43f5e", "#f97316", "#84cc16",
  "#ec4899", "#4f46e5", "#ef4444", "#22c55e",
]);

/**
 * הצבע שבו משמרת מוצגת בפועל.
 *
 * צבע שהמשתמש בחר בעצמו נשמר כמו שהוא — רק ברירות מחדל ישנות מוחלפות.
 */
export function shiftTone(color, type) {
  const c = String(color || "").toLowerCase();
  if (!c || LEGACY.has(c)) return SHIFT_TONES[type] || SHIFT_TONES.custom;
  return color;
}
